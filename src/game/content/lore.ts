function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function randomLore(s?: GameState): string {
  const pool = [...LORE_COMMON];
  if (s) pool.push(...(LORE_AREA[s.player.area] || []));
  return pick(pool);
}
